def generate_sample_ass(output_ass_path, is_vertical=True):
    res_x = 1080 if is_vertical else 1920
    res_y = 1920 if is_vertical else 1080
    font_size = 85 if is_vertical else 65
    margin_v = 650 if is_vertical else 120 # Placed perfectly in upper-lower third

    header = ASS_HEADER_TEMPLATE.format(
        res_x=res_x,
        res_y=res_y,
        font="Impact",
        font_size=font_size,
        outline=10,
        shadow=4,
        align=2, # Center-bottom
        margin_v=margin_v
    )

    # Sample dialogue lines demonstrating bounce animation and color pop
    dialogues = [
        "Dialogue: 0,0:00:00.50,0:00:01.40,Default,,0,0,0,,{\\t(0,100,\\fscx115\\fscy115)\\t(100,200,\\fscx100\\fscy100)}BÍ MẬT {\\c&H00FFFF&}ĐỈNH CAO\\N{\\r}CỦA VIDEO TRIỆU VIEW",
        "Dialogue: 0,0:00:01.45,0:00:02.50,Default,,0,0,0,,{\\t(0,100,\\fscx115\\fscy115)\\t(100,200,\\fscx100\\fscy100)}NẰM Ở CHÍNH {\\c&H0055FF&}TÂM ĐIỂM\\N{\\r}ÁNH NHÌN KHÁN GIẢ",
        "Dialogue: 0,0:00:02.55,0:00:03.80,Default,,0,0,0,,{\\t(0,100,\\fscx115\\fscy115)\\t(100,200,\\fscx100\\fscy100)}VÀ NHỊP CẮT {\\c&H00FF00&}HOÀN HẢO\\N{\\r}THEO TỪNG GIÂY!"
    ]

    content = header + "\n".join(dialogues) + "\n"
    with open(output_ass_path, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"[SUCCESS] Kinetic ASS Subtitle generated at: {output_ass_path}")

def burn_subtitles(video_input, ass_file, video_output):
    """Burns ASS subtitles into video using FFmpeg with proper path escaping."""
    # Escape backslashes for FFmpeg filter on Windows
    escaped_ass = ass_file.replace("\\", "/").replace(":", "\\:")
    cmd = [
        "ffmpeg", "-y",
        "-i", video_input,
        "-vf", f"subtitles='{escaped_ass}'",
        "-c:v", "libx264", "-preset", "slow", "-crf", "18",
        "-c:a", "copy",
        video_output
    ]
    print(f"[RUNNING Subtitle Burn]: {video_input} + {ass_file} -> {video_output}")
    subprocess.run(cmd, check=True)
    print(f"[SUCCESS] Burned subtitle video saved to: {video_output}")

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Subtitle Burn Engine - Kinetic ASS Generator")
    subparsers = parser.add_subparsers(dest="cmd")

    p_gen = subparsers.add_parser("create-template")
    p_gen.add_argument("output_ass")
    p_gen.add_argument("--vertical", action="store_true", default=True, help="9:16 vertical mode (default: True)")

    p_burn = subparsers.add_parser("burn")
    p_burn.add_argument("input_video")
    p_burn.add_argument("ass_file")
    p_burn.add_argument("output_video")

    args = parser.parse_args()
    if args.cmd == "create-template":
        generate_sample_ass(args.output_ass, is_vertical=args.vertical)
    elif args.cmd == "burn":
        burn_subtitles(args.input_video, args.ass_file, args.output_video)
    else:
        parser.print_help()
